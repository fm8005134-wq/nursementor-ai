def _title_for_text(patient):
    t = _title_for(patient)
    name = patient["name"]
    return ("{} {}".format(t, name)).strip()


def build_patient_report_text(patient_id):
    patient = db.get_patient(patient_id)
    if not patient:
        return "Patient not found."

    visits = db.get_patient_visits(patient_id)

    lines = []
    lines.append("=" * 60)
    lines.append(CLINIC_NAME.center(60))
    lines.append(CLINIC_QUALIFICATION.center(60))
    lines.append(CLINIC_SPECIALTY.center(60))
    lines.append("Contact: {}   Timing: {}".format(CLINIC_CONTACT, CLINIC_TIMING).center(60))
    lines.append("=" * 60)
    lines.append("")
    lines.append("PATIENT REPORT".center(60))
    lines.append("")
    lines.append("-" * 60)
    lines.append("Patient ID   : {}".format(patient["id"]))
    lines.append("Name         : {}".format(_title_for_text(patient)))
    lines.append("Age          : {}".format(patient.get("age") or "-"))
    lines.append("Gender       : {}".format((patient.get("gender") or "-").upper()))
    lines.append("Phone        : {}".format(patient.get("phone") or "-"))
    lines.append("Address      : {}".format(patient.get("address") or "-"))
    lines.append("Registered   : {}".format(patient.get("created_at") or "-"))
    lines.append("Total Visits : {}".format(len(visits)))
    lines.append("")
    lines.append("Report generated: {}".format(
        datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    ))
    lines.append("-" * 60)
    lines.append("VISIT HISTORY")
    lines.append("-" * 60)
    lines.append("")

    if not visits:
        lines.append("No visits recorded.")
    else:
        total = len(visits)
        for i, visit in enumerate(visits):
            visit_no = total - i
            lines.append("Visit #{}  -  {}".format(visit_no, visit["visit_date"]))
            lines.append("")
            procs = db.get_visit_procedures(visit["id"])
            tests = db.get_visit_tests(visit["id"])
            if not procs and not tests:
                lines.append("    (No procedures or tests)")
                lines.append("")
                continue
            if procs:
                lines.append("    Procedures:")
                for p in procs:
                    text = "      - {}".format(p["name"])
                    if p.get("details"):
                        text += "  ({})".format(p["details"])
                    lines.append(text)
                lines.append("")
            if tests:
                lines.append("    Tests:")
                for t in tests:
                    text = "      - {}".format(t["name"])
                    if t.get("result"):
                        text += "  Result: {}".format(t["result"])
                    else:
                        text += "  Result: Pending"
                    lines.append(text)
                lines.append("")

    lines.append("=" * 60)
    lines.append("Prepared by: {}".format(PREPARER_NAME))
    lines.append("Date: {}".format(datetime.now().strftime("%Y-%m-%d")))
    lines.append("=" * 60)

    return "\n".join(lines)


def save_patient_report_text(patient_id):
    patient = db.get_patient(patient_id)
    if not patient:
        return None

    _ensure_reports_dir()
    safe_name = "".join(c if c.isalnum() else "_" for c in patient["name"])
    date_str = datetime.now().strftime("%Y-%m-%d")
    filename = "patient_{}_{}_{}.txt".format(patient["id"], safe_name, date_str)
    filepath = os.path.join(REPORTS_DIR, filename)

    try:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(build_patient_report_text(patient_id))
        return filepath
    except Exception:
        return None